/** 글의 기준 날짜: 예약 발행일 → 수정일 → 기본 날짜 순으로 쓴다. */
export function cultureDate(item: CultureItem): string {
  return item.publishAt ?? item.updatedAt ?? CULTURE_BASE_DATE;
}

function todayInSeoul(now: Date): string {
  return new Intl.DateTimeFormat("sv-SE", { timeZone: "Asia/Seoul" }).format(now);
}

/**
 * 지금 공개된 글만 최신순으로 돌려준다. 날짜가 같으면 원래 순서를 지킨다.
 * 페이지들은 revalidate로 1시간마다 다시 만들어지므로, 발행일이 되면 1시간 안에 나타난다.
 */
export function getPublishedCultureItems(now: Date = new Date()): CultureItem[] {
  const today = todayInSeoul(now);
  return allCultureItems
    .filter((item) => !item.publishAt || item.publishAt <= today)
    .map((item, index) => ({ item, index }))
    .sort((a, b) => cultureDate(b.item).localeCompare(cultureDate(a.item)) || a.index - b.index)
    .map(({ item }) => item);
}

/** 예약 글까지 포함한 전체 목록(점검용). 화면에는 쓰지 않는다. */
export function getAllCultureItemsForCheck(): CultureItem[] {
  return allCultureItems;
}
